//! Manifest-mirror immutability and workspace inheritance, exercised through the CLI.

#![cfg(feature = "cli")]

use serde_json::Value;
use std::path::Path;

mod support;

use support::run_cli;

fn put(root: &Path, path: &str, text: &str) {
    let file = root.join(path);
    std::fs::create_dir_all(file.parent().unwrap()).unwrap();
    std::fs::write(file, text).unwrap();
}

fn scan(root: &Path, args: &[&str]) -> Value {
    let mut all: Vec<&str> = vec![
        "--context-blocks",
        "--context-min-tokens",
        "0",
        "--no-fail",
        "--json",
    ];
    all.extend_from_slice(args);
    let output = run_cli(root, &all);
    let status = output.status;
    let stdout = String::from_utf8_lossy(&output.stdout).into_owned();
    let stderr = String::from_utf8_lossy(&output.stderr).into_owned();
    assert!(
        status.success(),
        "status {status} stdout {stdout} stderr {stderr}"
    );
    serde_json::from_slice(&output.stdout).unwrap()
}

fn packages(report: &Value) -> Vec<String> {
    let groups = report["reuse"]["groups"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    let mut names: Vec<String> = groups
        .iter()
        .flat_map(|group| group["candidates"].as_array().cloned().unwrap_or_default())
        .map(|candidate| candidate["package"].as_str().unwrap_or_default().to_owned())
        .collect();
    names.sort();
    names.dedup();
    names
}

fn snapshot(root: &Path, rels: &[&str]) -> Vec<(String, Vec<u8>)> {
    rels.iter()
        .map(|rel| (rel.to_string(), std::fs::read(root.join(rel)).unwrap()))
        .collect()
}

fn assert_untouched(root: &Path, before: &[(String, Vec<u8>)]) {
    for (rel, bytes) in before {
        let now = std::fs::read(root.join(rel)).unwrap_or_default();
        assert_eq!(now, *bytes, "scan modified the original {rel}");
    }
}

/// A workspace with two members and two excluded, standalone-workspace path
/// dependencies, mirroring the corpus fixture.
fn fixture_a(with_lock: bool) -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    put(
        root,
        "Cargo.toml",
        "[workspace]\nresolver = \"3\"\nmembers = [\"app\", \"other\"]\nexclude = [\"deps/direct\", \"deps/transitive\"]\n",
    );
    put(
        root,
        "app/Cargo.toml",
        "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2024\"\n[dependencies]\ndirect = { path = \"../deps/direct\" }\n",
    );
    put(
        root,
        "app/src/lib.rs",
        "pub fn selected(value: u32) -> u32 { let total = value + 1u32; total * 2u32 }\n",
    );
    put(
        root,
        "other/Cargo.toml",
        "[package]\nname = \"other\"\nversion = \"0.1.0\"\nedition = \"2024\"\n",
    );
    put(
        root,
        "other/src/lib.rs",
        "pub fn available(input: u32) -> u32 { let result = input + 1u32; result * 2u32 }\n",
    );
    put(
        root,
        "deps/direct/Cargo.toml",
        "[package]\nname = \"direct\"\nversion = \"0.1.0\"\nedition = \"2024\"\n[dependencies]\ntransitive = { path = \"../transitive\" }\n[workspace]\n",
    );
    put(
        root,
        "deps/direct/src/lib.rs",
        "pub fn helper(input: u32) -> u32 { let result = input + 1u32; result * 2u32 }\n",
    );
    put(
        root,
        "deps/transitive/Cargo.toml",
        "[package]\nname = \"transitive\"\nversion = \"0.1.0\"\nedition = \"2024\"\n[workspace]\n",
    );
    put(
        root,
        "deps/transitive/src/lib.rs",
        "pub fn helper(input: u32) -> u32 { input + 7u32 }\n",
    );
    if with_lock {
        put(
            root,
            "Cargo.lock",
            "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\"direct\"]\n\n[[package]]\nname = \"direct\"\nversion = \"0.1.0\"\ndependencies = [\"transitive\"]\n\n[[package]]\nname = \"other\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"transitive\"\nversion = \"0.1.0\"\n",
        );
    }
    dir
}

/// A member and a member library, with version, edition and the dependency
/// inherited from the workspace tables, and an auto-discovered bin target.
fn fixture_b() -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    put(
        root,
        "Cargo.toml",
        "[workspace]\nresolver = \"3\"\nmembers = [\"app\", \"lib\"]\n[workspace.package]\nversion = \"0.1.0\"\nedition = \"2024\"\n[workspace.dependencies]\nlib = { path = \"lib\" }\n",
    );
    put(
        root,
        "app/Cargo.toml",
        "[package]\nname = \"app\"\nversion.workspace = true\nedition.workspace = true\n[dependencies]\nlib = { workspace = true }\n",
    );
    put(
        root,
        "app/src/lib.rs",
        "pub fn selected(value: u32) -> u32 { let total = value + 1u32; total * 2u32 }\n",
    );
    put(root, "app/src/main.rs", "fn main() {}\n");
    put(
        root,
        "lib/Cargo.toml",
        "[package]\nname = \"lib\"\nversion.workspace = true\nedition.workspace = true\n",
    );
    put(
        root,
        "lib/src/lib.rs",
        "pub fn available(input: u32) -> u32 { let result = input + 1u32; result * 2u32 }\n",
    );
    dir
}

