#[test]
fn dependency_scan_keeps_original_manifests_and_lockfile() {
    let dir = fixture_a(true);
    let root = dir.path();
    let rels = [
        "Cargo.toml",
        "Cargo.lock",
        "app/Cargo.toml",
        "app/src/lib.rs",
        "other/Cargo.toml",
        "other/src/lib.rs",
        "deps/direct/Cargo.toml",
        "deps/direct/src/lib.rs",
        "deps/transitive/Cargo.toml",
        "deps/transitive/src/lib.rs",
    ];
    let before = snapshot(root, &rels);
    let cache = root.join("index");
    let cache = cache.to_str().unwrap();
    let report = scan(
        root,
        &[
            "--context-select",
            "crate:app",
            "--context-dependency-depth",
            "1",
            "--context-check-latest",
            "false",
            "--context-cache-dir",
            cache,
        ],
    );
    assert_eq!(packages(&report), ["direct"]);
    assert_untouched(root, &before);
    assert!(
        root.join("Cargo.lock").exists(),
        "original lockfile was removed"
    );
}

#[test]
fn dependency_scan_preserves_absent_lockfile() {
    let dir = fixture_a(false);
    let root = dir.path();
    let rels = ["Cargo.toml", "app/Cargo.toml", "deps/direct/Cargo.toml"];
    let before = snapshot(root, &rels);
    let cache = root.join("index");
    let cache = cache.to_str().unwrap();
    let report = scan(
        root,
        &[
            "--context-select",
            "crate:app",
            "--context-dependency-depth",
            "1",
            "--context-check-latest",
            "false",
            "--context-cache-dir",
            cache,
        ],
    );
    assert_eq!(packages(&report), ["direct"]);
    assert_untouched(root, &before);
    assert!(
        !root.join("Cargo.lock").exists(),
        "scan created an original Cargo.lock"
    );
}

