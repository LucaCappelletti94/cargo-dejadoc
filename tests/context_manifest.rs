/// A workspace whose root carries a cargo config file the scan must honor and
/// leave untouched, with an excluded, standalone-workspace path dependency.
fn fixture_d() -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    put(
        root,
        "Cargo.toml",
        "[workspace]\nresolver = \"3\"\nmembers = [\"app\"]\nexclude = [\"direct\"]\n",
    );
    put(root, ".cargo/config.toml", "[term]\ncolor = \"never\"\n");
    put(
        root,
        "app/Cargo.toml",
        "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2024\"\n[dependencies]\ndirect = { path = \"../direct\" }\n",
    );
    put(
        root,
        "app/src/lib.rs",
        "pub fn selected(value: u32) -> u32 { let total = value + 1u32; total * 2u32 }\n",
    );
    put(
        root,
        "direct/Cargo.toml",
        "[package]\nname = \"direct\"\nversion = \"0.1.0\"\nedition = \"2024\"\n[workspace]\n",
    );
    put(
        root,
        "direct/src/lib.rs",
        "pub fn helper(input: u32) -> u32 { let result = input + 1u32; result * 2u32 }\n",
    );
    dir
}

#[test]
fn original_cargo_config_is_honored_and_untouched() {
    let dir = fixture_d();
    let root = dir.path();
    let config = root.join(".cargo/config.toml");
    let before = std::fs::read(&config).unwrap();
    let cache = root.join("index");
    let cache = cache.to_str().unwrap();
    let report = scan(
        root,
        &[
            "--context-select",
            "crate:app",
            "--context-dependency-depth",
            "1",
            "--context-check-latest",
            "false",
            "--context-cache-dir",
            cache,
        ],
    );
    assert_eq!(packages(&report), ["direct"]);
    assert_eq!(
        std::fs::read(&config).unwrap(),
        before,
        "scan modified the original cargo config"
    );
}
